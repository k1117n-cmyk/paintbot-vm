"""Generate VM-only seekers with a distance-sorted fixed-map lookup table.

Each position has 36 pairs of ASCII coordinates plus a NUL (73 bytes).
The live board decides whether a candidate still exists. Input lives at
65536 so it cannot overwrite the approximately 20KB program and tables.
"""
from pathlib import Path

COORDS = (2, 4, 6, 9, 11, 13)


def candidates(x, y, vertical):
    return sorted(((tx, ty) for ty in COORDS for tx in COORDS),
                  key=lambda p: (abs(x - p[0]) + abs(y - p[1]),
                                 p[0] if vertical else p[1],
                                 p[1] if vertical else p[0]))


def assembly(vertical=False):
    source = '''; Generated by generate_seekers.py. Do not edit by hand.
; Read and discard the 10-byte TREASURE1 identification line.
MOVI R1, 10
magic:
SYSCALL 2
DEC R1
MOVI R0, 0
CMP R1, R0
JNZ magic
; Store board and header at 65536, then N twelve-byte position/score records.
MOVI R1, 65536
MOVI R2, 65816
read_header:
SYSCALL 2
STB [R1], R0
INC R1
CMP R1, R2
JNZ read_header
MOVI R2, 65814
LDB R2, [R2]
MOVI R0, 48
SUB R2, R0
MOVI R4, 0
read_position:
MOVI R3, 0
read_record:
SYSCALL 2
STB [R1], R0
INC R1
INC R3
MOVI R0, 12
CMP R3, R0
JNZ read_record
INC R4
CMP R4, R2
JNZ read_position
MOVI R1, 65808
LDB R2, [R1]
MOVI R0, 49
SUB R2, R0
MOVI R1, 65818
record_offset:
MOVI R0, 0
CMP R2, R0
JZ own_record
MOVI R0, 12
ADD R1, R0
DEC R2
JUMP record_offset
own_record:
; Break lockstep on overlaps: lowest ID waits; the others step aside.
; Compare five raw coordinate bytes (XX YY), excluding ID and score.
MOV R7, R1
MOVI R6, 65818
MOVI R3, 0
MOVI R4, 65814
LDB R4, [R4]
MOVI R0, 48
SUB R4, R0
overlap_record:
CMP R6, R7
JZ overlap_self
MOV R1, R6
MOV R2, R7
LDB R0, [R1]
LDB R5, [R2]
CMP R0, R5
JNZ overlap_next
INC R1
INC R2
LDB R0, [R1]
LDB R5, [R2]
CMP R0, R5
JNZ overlap_next
INC R1
INC R2
LDB R0, [R1]
LDB R5, [R2]
CMP R0, R5
JNZ overlap_next
INC R1
INC R2
LDB R0, [R1]
LDB R5, [R2]
CMP R0, R5
JNZ overlap_next
INC R1
INC R2
LDB R0, [R1]
LDB R5, [R2]
CMP R0, R5
JNZ overlap_next
INC R1
INC R2
MOVI R0, 0
CMP R3, R0
JZ yield_overlap
MOVI R0, 88
JUMP output
overlap_self:
MOVI R3, 1
overlap_next:
MOVI R0, 12
ADD R6, R0
DEC R4
MOVI R0, 0
CMP R4, R0
JNZ overlap_record
MOV R1, R7
JUMP decode_own
yield_overlap:
; Step right, except at the right edge where we step left.
MOV R1, R7
LDB R0, [R1]
MOVI R5, 49
CMP R0, R5
JNZ right
INC R1
LDB R0, [R1]
MOVI R5, 53
CMP R0, R5
JZ left
JUMP right
decode_own:
CALLI coordinate
MOV R3, R0
INC R1
INC R1
CALLI coordinate
MOV R4, R0
; R3=own x, R4=own y. Locate 73-byte candidate list for this position.
MOVI R6, targets
MOV R1, R4
table_rows:
MOVI R0, 0
CMP R1, R0
JZ table_columns
MOVI R0, 1168
ADD R6, R0
DEC R1
JUMP table_rows
table_columns:
MOV R1, R3
table_column:
MOVI R0, 0
CMP R1, R0
JZ search_start
MOVI R0, 73
ADD R6, R0
DEC R1
JUMP table_column
search_start:
MOVI R7, 36
search:
LDB R1, [R6]
INC R6
LDB R2, [R6]
INC R6
MOVI R0, 65
SUB R1, R0
SUB R2, R0
; Skip our own cell: a disputed treasure must not trap both seekers forever.
CMP R1, R3
JNZ check_treasure
CMP R2, R4
JZ next
check_treasure:
MOVI R5, 65536
ADD R5, R1
MOV R0, R2
board_row:
MOVI R0, 0
CMP R2, R0
JZ board_cell
MOVI R0, 17
ADD R5, R0
DEC R2
JUMP board_row
board_cell:
LDB R0, [R5]
MOVI R5, 46
CMP R0, R5
JZ next
; Restore target y, which board addressing consumed.
MOV R5, R6
DEC R5
LDB R2, [R5]
MOVI R0, 65
SUB R2, R0
'''
    source += ('CMP R2, R4\nJNZ choose_y\nJUMP choose_x\n' if vertical
               else 'CMP R1, R3\nJNZ choose_x\nJUMP choose_y\n')
    source += '''choose_x:
MOV R0, R1
MOV R5, R3
compare_x:
MOVI R1, 0
CMP R0, R1
JZ left
CMP R5, R1
JZ right
DEC R0
DEC R5
JUMP compare_x
choose_y:
MOV R0, R2
MOV R5, R4
compare_y:
MOVI R1, 0
CMP R0, R1
JZ up
CMP R5, R1
JZ down
DEC R0
DEC R5
JUMP compare_y
next:
DEC R7
MOVI R0, 0
CMP R7, R0
JNZ search
MOVI R0, 88
JUMP output
left:
MOVI R0, 65
JUMP output
right:
MOVI R0, 68
JUMP output
up:
MOVI R0, 87
JUMP output
down:
MOVI R0, 83
output:
SYSCALL 0
HALT
; Decode a two-digit coordinate at R1; leave R1 pointing at the ones digit.
coordinate:
LDB R0, [R1]
INC R1
MOVI R2, 49
CMP R0, R2
JZ tens_one
LDB R0, [R1]
MOVI R2, 48
SUB R0, R2
RET
tens_one:
LDB R0, [R1]
MOVI R2, 48
SUB R0, R2
MOVI R2, 10
ADD R0, R2
RET
targets:
'''
    for y in range(16):
        for x in range(16):
            pairs = ''.join(chr(65 + tx) + chr(65 + ty)
                            for tx, ty in candidates(x, y, vertical))
            source += f'.STRING "{pairs}"\n'
    return source


if __name__ == '__main__':
    for suffix, vertical in [('h', False), ('v', True)]:
        Path(__file__).with_name(f'seeker-{suffix}.asm').write_text(assembly(vertical))
