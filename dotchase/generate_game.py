"""Generate a VM game and a shortest-path table for its fixed maze.

The resulting bytecode owns movement, pellets, collisions, enemy turns and
win/loss state. Python runs only at development/build time, never during play.
"""
from collections import deque
from pathlib import Path

LEVEL = (
    '################',
    '#              #',
    '# ## ##  ## ## #',
    '#              #',
    '# ## ###### ## #',
    '#              #',
    '# #### ## #### #',
    '#              #',
    '# ## ##  ## ## #',
    '#              #',
    '################',
)
VARIABLES = {name: 67200+i for i, name in enumerate(
    ('player', 'ghost', 'direction', 'ticks', 'score', 'remaining', 'state', 'cooldown'))}
BOARD, FRAME = 65536, 66048
DELTAS = (('w', -16), ('a', -1), ('s', 16), ('d', 1))


def assembly(level=LEVEL, player=17, ghost=158, interval=20, player_ticks=8, enemy_ticks=24):
    assert len(level) == 11 and all(len(row) == 16 for row in level)
    assert all(row[0] == row[-1] == '#' for row in level)
    assert level[0] == level[-1] == '#' * 16
    original = ''.join(level)
    assert set(original) <= {'#', ' '}
    walkable = {i for i, cell in enumerate(original) if cell != '#'}
    assert player in walkable and ghost in walkable and player != ghost
    dots = len(walkable) - 1
    assert 0 < dots < 100 and 1 <= interval <= 1000
    assert 1 <= player_ticks <= 255 and 1 <= enemy_ticks <= 255
    board = ''.join(' ' if i == player else '.' if i in walkable else '#' for i in range(176))
    paths = [['x']*176 for _ in range(176)]
    for target in sorted(walkable):
        distances = {target: 0}
        queue = deque([target])
        while queue:
            current = queue.popleft()
            for _, delta in DELTAS:
                adjacent = current + delta
                if adjacent in walkable and adjacent not in distances:
                    distances[adjacent] = distances[current] + 1
                    queue.append(adjacent)
        assert set(distances) == walkable, 'maze must be connected'
        for current in walkable - {target}:
            paths[current][target] = next(key for key, delta in DELTAS
                                         if distances.get(current+delta) == distances[current]-1)
    lines = [
        'Dot Chase (VM)', f'Dots: 00/{dots:02}   @: you  G: enemy', '',
        *['']*11, '', 'W/A/S/D: step  X: cancel',
        'R: restart  Q: back', 'Collect dots. Avoid G!',
    ]
    assert len(lines) == 18 and all(len(line) <= 32 for line in lines)
    code = f'''; Generated by generate_game.py. Game logic executes in the VM.
; R7 is reserved for variable access. Board={BOARD}, frame={FRAME}.
restart:
MOVI R0, initial_board
MOVI R1, {BOARD}
MOVI R2, {BOARD+176}
copy_board:
LDB R3, [R0]
STB [R1], R3
INC R0
INC R1
CMP R1, R2
JNZ copy_board
MOVI R0, {player}
SET player R0
MOVI R0, {ghost}
SET ghost R0
MOVI R0, 0
SET ticks R0
SET score R0
SET state R0
SET cooldown R0
MOVI R0, 120
SET direction R0
MOVI R0, {dots}
SET remaining R0
CALLI render
main_loop:
MOVI R0, {interval}
SYSCALL 6
; A direction is valid only for this input poll, never retained as auto-run.
MOVI R0, 120
SET direction R0
GET cooldown R0
MOVI R1, 0
CMP R0, R1
JZ input_start
DEC R0
SET cooldown R0
input_start:
; Consume a bounded burst, keeping the latest direction for one move.
; Q/R are handled immediately and never drain the launcher's next command.
MOVI R6, 32
read_key:
SYSCALL 5
MOVI R1, 0
CMP R0, R1
JZ input_done
MOVI R1, 256
CMP R0, R1
JZ quit
MOVI R1, 113
CMP R0, R1
JZ quit
MOVI R1, 81
CMP R0, R1
JZ quit
MOVI R1, 114
CMP R0, R1
JZ restart
MOVI R1, 82
CMP R0, R1
JZ restart
GET state R1
MOVI R2, 0
CMP R1, R2
JNZ result_input
'''
    for key in 'wasdx':
        code += f'''MOVI R1, {ord(key)}
CMP R0, R1
JZ direction_{key}
MOVI R1, {ord(key.upper())}
CMP R0, R1
JZ direction_{key}
'''
    code += 'JUMP next_key\n'
    for key in 'wasdx':
        code += f'''direction_{key}:
MOVI R0, {ord(key)}
SET direction R0
JUMP next_key
'''
    code += f'''next_key:
DEC R6
MOVI R1, 0
CMP R6, R1
JNZ read_key
input_done:
GET state R0
MOVI R1, 0
CMP R0, R1
JNZ main_loop
player_step:
GET cooldown R0
MOVI R1, 0
CMP R0, R1
JNZ enemy_turn
GET player R5
MOV R0, R5
GET direction R1
CALLI try_move
CMP R0, R5
JZ enemy_turn
SET player R0
MOVI R2, {player_ticks}
SET cooldown R2
GET ghost R1
CMP R0, R1
JZ lost
MOVI R1, {BOARD}
ADD R1, R0
LDB R2, [R1]
MOVI R3, 46
CMP R2, R3
JNZ enemy_turn
MOVI R2, 32
STB [R1], R2
GET score R0
INC R0
SET score R0
GET remaining R0
DEC R0
SET remaining R0
enemy_turn:
GET ticks R0
INC R0
MOVI R1, {enemy_ticks}
CMP R0, R1
JZ move_enemy
SET ticks R0
JUMP after_enemy
move_enemy:
MOVI R0, 0
SET ticks R0
GET ghost R0
MOVI R2, paths
MOVI R3, 177
MOVI R4, 0
enemy_row:
CMP R0, R4
JZ enemy_column
ADD R2, R3
DEC R0
JUMP enemy_row
enemy_column:
GET player R1
ADD R2, R1
LDB R1, [R2]
GET ghost R0
CALLI try_move
SET ghost R0
after_enemy:
GET player R0
GET ghost R1
CMP R0, R1
JZ lost
GET remaining R0
MOVI R1, 0
CMP R0, R1
JZ won
CALLI render
JUMP main_loop
won:
MOVI R0, 1
SET state R0
CALLI render
JUMP main_loop
lost:
MOVI R0, 2
SET state R0
CALLI render
JUMP main_loop
result_input:
MOVI R1, 10
CMP R0, R1
JZ quit
MOVI R1, 13
CMP R0, R1
JZ quit
JUMP next_key
quit:
HALT
; R0=position, R1=direction -> R0=next position (walls block).
try_move:
MOV R2, R0
MOVI R3, 119
CMP R1, R3
JZ move_up
MOVI R3, 97
CMP R1, R3
JZ move_left
MOVI R3, 115
CMP R1, R3
JZ move_down
MOVI R3, 100
CMP R1, R3
JZ move_right
RET
move_up:
MOVI R3, 16
SUB R2, R3
JUMP check_wall
move_left:
DEC R2
JUMP check_wall
move_down:
MOVI R3, 16
ADD R2, R3
JUMP check_wall
move_right:
INC R2
check_wall:
MOVI R4, {BOARD}
ADD R4, R2
LDB R4, [R4]
MOVI R3, 35
CMP R4, R3
JZ blocked
MOV R0, R2
blocked:
RET
; Compose a printable 32x18 frame in VM memory.
render:
MOVI R0, frame_template
MOVI R1, {FRAME}
MOVI R2, {FRAME+576}
MOVI R3, 32
copy_frame:
LDB R4, [R0]
STB [R1], R4
INC R0
INC R1
DEC R3
MOVI R4, 0
CMP R3, R4
JNZ copy_frame
INC R0
MOVI R3, 32
CMP R1, R2
JNZ copy_frame
MOVI R0, {BOARD}
MOVI R1, {FRAME+96}
MOVI R2, 0
MOVI R3, 0
GET player R5
GET ghost R6
render_cell:
LDB R4, [R0]
CMP R2, R5
JZ draw_player
CMP R2, R6
JZ draw_enemy
JUMP put_cell
draw_player:
MOVI R4, 64
CMP R2, R6
JNZ put_cell
MOVI R4, 33
JUMP put_cell
draw_enemy:
MOVI R4, 71
put_cell:
STB [R1], R4
INC R0
INC R1
INC R2
INC R3
MOVI R4, 16
CMP R3, R4
JNZ render_cell
ADD R1, R4
MOVI R3, 0
MOVI R4, 176
CMP R2, R4
JNZ render_cell
GET score R0
MOVI R1, 48
MOVI R2, 48
score_digit:
MOVI R3, 0
CMP R0, R3
JZ put_score
DEC R0
INC R2
MOVI R3, 58
CMP R2, R3
JNZ score_digit
MOVI R2, 48
INC R1
JUMP score_digit
put_score:
MOVI R3, {FRAME+38}
STB [R3], R1
INC R3
STB [R3], R2
GET state R0
MOVI R1, 0
CMP R0, R1
JZ present
MOVI R1, 1
CMP R0, R1
JZ win_message
MOVI R0, lose_message
JUMP status_message
win_message:
MOVI R0, win_message_text
status_message:
MOVI R1, {FRAME+17*32}
MOVI R2, {FRAME+18*32}
copy_status:
LDB R3, [R0]
STB [R1], R3
INC R0
INC R1
CMP R1, R2
JNZ copy_status
present:
MOVI R0, {FRAME}
SYSCALL 4
RET
initial_board:
.STRING "{board}"
frame_template:
'''
    code += ''.join(f'.STRING "{line.ljust(32)}"\n' for line in lines)
    code += 'win_message_text:\n.STRING "' + 'Cleared! Enter/Q: back R: retry'.ljust(32) + '"\n'
    code += 'lose_message:\n.STRING "' + 'Caught! Enter/Q: back R: retry'.ljust(32) + '"\n'
    code += 'paths:\n' + ''.join('.STRING "'+''.join(row)+'"\n' for row in paths)
    expanded = []
    for line in code.splitlines():
        parts = line.split()
        if parts and parts[0] in ('GET', 'SET'):
            operation, name, register = parts
            expanded.append(f'MOVI R7, {VARIABLES[name]}')
            expanded.append(f'LDB {register}, [R7]' if operation == 'GET' else f'STB [R7], {register}')
        else:
            expanded.append(line)
    return '\n'.join(expanded)+'\n'


if __name__ == '__main__':
    Path(__file__).with_name('game.asm').write_text(assembly())
