"""Generate readable assembly; runtime is entirely the existing handmade VM.

The 16x16 tour is a Hamiltonian cycle: reserve column zero as the return
lane, snake across columns 1..15, then return up column zero. Transpose
coordinates/actions for the vertical variant. No Python is used by a bot.
"""
from pathlib import Path

NAMES = ('explorer-h', 'explorer-v', 'raider-h', 'raider-v')


def tour(x, y, vertical=False):
    if vertical:
        return dict(D='S', S='D', A='W', W='A')[tour(y, x)]
    if x == 0:
        return 'D' if y == 0 else 'W'
    if y == 15:
        return 'A'
    if y % 2 == 0:
        return 'S' if x == 15 else 'D'
    return 'S' if x == 1 else 'A'


def assembly(name):
    vertical = name.endswith('-v')
    raider = name.startswith('raider')
    text = '''; Generated by game/bots/generate_strategies.py. Do not edit by hand.
; Read the board and full header at 16384; then exactly N position records.
; R3=x R4=y R5=board address R6=tour action R7=own color (ASCII ID).
MOVI R1, 16384
MOVI R2, 16664
read_header:
SYSCALL 2
STB [R1], R0
INC R1
CMP R1, R2
JNZ read_header
MOVI R2, 16662
LDB R2, [R2]
MOVI R0, 48
SUB R2, R0
MOVI R4, 0
read_position:
MOVI R3, 0
read_record:
SYSCALL 2
STB [R1], R0
INC R1
INC R3
MOVI R0, 8
CMP R3, R0
JNZ read_record
INC R4
CMP R4, R2
JNZ read_position
; Locate own record (ID order), then decode its two decimal coordinates.
MOVI R1, 16656
LDB R7, [R1]
MOV R2, R7
MOVI R0, 49
SUB R2, R0
MOVI R1, 16666
record_offset:
MOVI R0, 0
CMP R2, R0
JZ own_record
MOVI R0, 8
ADD R1, R0
DEC R2
JUMP record_offset
own_record:
CALLI coordinate
MOV R3, R0
INC R1
INC R1
CALLI coordinate
MOV R4, R0
; Address = board base + y*17 + x (the board has LF after each row).
MOVI R5, 16384
ADD R5, R3
MOV R1, R4
row_offset:
MOVI R0, 0
CMP R1, R0
JZ choose
MOVI R0, 17
ADD R5, R0
DEC R1
JUMP row_offset
choose:
MOV R1, R5
MOVI R0, 16384
SUB R1, R0
MOVI R0, tour_table
ADD R1, R0
LDB R6, [R1]
'''
    order = 'SDWA' if vertical else 'DSAW'
    for phase in range(2):
        for i, action in enumerate([None, *order]):
            label = f'next_{phase}_{i}'
            text += ('MOV R0, R6\n' if action is None else f'MOVI R0, {ord(action)}\n')
            text += f'CALLI neighbor\nCMP R1, R7\nJZ {label}\n'
            if phase == 0:
                text += 'MOVI R2, 46\nCMP R1, R2\n'
                text += ('JNZ output\n' if raider else 'JZ output\n')
            else:
                text += 'JUMP output\n'
            text += label + ':\n'
    text += '''; All adjacent cells are ours: keep moving along the tour.
MOV R0, R6
output:
SYSCALL 0
HALT
; R1 points to tens; returns numeric coordinate in R0, pointer at ones.
coordinate:
LDB R0, [R1]
INC R1
MOVI R2, 49
CMP R0, R2
JZ tens_one
LDB R0, [R1]
MOVI R2, 48
SUB R0, R2
RET
tens_one:
LDB R0, [R1]
MOVI R2, 48
SUB R0, R2
MOVI R2, 10
ADD R0, R2
RET
; R0=action; return adjacent color in R1, own color for out-of-bounds.
; R0 and R3..R7 survive; only R1/R2 are scratch.
neighbor:
MOV R1, R5
MOVI R2, 87
CMP R0, R2
JZ up
MOVI R2, 65
CMP R0, R2
JZ left
MOVI R2, 83
CMP R0, R2
JZ down
MOVI R2, 15
CMP R3, R2
JZ outside
INC R1
JUMP color
up:
MOVI R2, 0
CMP R4, R2
JZ outside
MOVI R2, 17
SUB R1, R2
JUMP color
left:
MOVI R2, 0
CMP R3, R2
JZ outside
DEC R1
JUMP color
down:
MOVI R2, 15
CMP R4, R2
JZ outside
MOVI R2, 17
ADD R1, R2
color:
LDB R1, [R1]
RET
outside:
MOV R1, R7
RET
; 16 bytes plus NUL per row: same stride as the input board.
tour_table:
'''
    for y in range(16):
        text += '.STRING "' + ''.join(tour(x, y, vertical) for x in range(16)) + '"\n'
    return text


if __name__ == '__main__':
    for name in NAMES:
        path = Path(__file__).parent / (name + '.asm')
        path.write_text(assembly(name))
        print(path)
